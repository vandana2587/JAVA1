package FUNCTIONS;

public class multi {
    public static int multi(int a,int b) {
        int prod=a*b;
        return prod;
        
    }
    public static void main(String[] args) {
       int a=10;
       int b=20;
        int prod=(a*b);
        System.out.println("product is="+prod);
        multi(10,20);
    }
}
